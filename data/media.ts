export function mediaById(id: string): MediaSlot | undefined {
  return media.find((m) => m.id === id);
}
/** The four anchors rendered first in Phase 8. */
export const ANCHOR_SLOTS = media.filter((m) => m.reference).map((m) => m.id);
/** Slots grouped by the admin Media screen's sections, in board order. */
export function mediaSections(): { sectionAr: string; slots: MediaSlot[] }[] {
  const order: string[] = [];
  for (const m of media) if (m.sectionAr && !order.includes(m.sectionAr)) order.push(m.sectionAr);
  return order.map((sectionAr) => ({ sectionAr, slots: media.filter((m) => m.sectionAr === sectionAr) }));
}
