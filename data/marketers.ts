export function marketerById(id: string): Marketer | undefined {
  const needle = id.toUpperCase();
  return marketers.find((m) => m.id === needle);
}
export function marketerBySlug(slug: string): Marketer | undefined {
  return marketers.find((m) => m.slug === slug.toLowerCase());
}
export function marketerByToken(token: string): Marketer | undefined {
  return marketers.find((m) => m.token === token.toLowerCase());
}
