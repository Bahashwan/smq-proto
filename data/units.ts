export function unitByCode(code: string): Unit | undefined {
  const c = code.toUpperCase();
  return units.find((u) => u.code === c);
}
export function unitBySlug(slug: string): Unit | undefined {
  return units.find((u) => u.slug === slug.toLowerCase());
}
/** «نموذج A» · «روف» (the project table's first column) */
export function modelLabel(unit: Unit): string {
  return unit.type === "roof-villa" ? "روف" : unit.model;
}
/** «الثالث» · «الرابع والسطح»; undefined when no floor is set */
export function floorLabel(unit: Unit): string | undefined {
  return unit.floor ? (FLOOR_WORDS[unit.floor.value] ?? unit.floor.value) : undefined;
}
