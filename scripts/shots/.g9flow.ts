import { launch, newPage, settle } from "./lib";
const browser = await launch();
const page = await newPage(browser, 1440, 900);
const errs: string[] = [];
page.on("pageerror", (e) => errs.push(e.message.slice(0, 300)));
page.on("console", (m) => { if (m.type() === "error") errs.push(m.text().slice(0, 300)); });
await page.goto("http://localhost:3000/admin/alliance/requests?req=REQ-2026-0412", { waitUntil: "load" });
await settle(page, 1500);
await page.getByRole("radio", { name: "اختر عرض مكتب ط" }).check();
await page.getByRole("button", { name: "أنشئ سجل إحالة" }).click();
await page.waitForURL(/referrals/, { timeout: 30000 });
await settle(page, 1500);
console.log("url:", page.url());
const store = await page.evaluate(() => sessionStorage.getItem("smq.store"));
const parsed = JSON.parse(store ?? "{}");
console.log("created:", JSON.stringify(parsed.state?.createdReferrals?.map((r: { id: string; stage: string }) => [r.id, r.stage])), "req:", JSON.stringify(parsed.state?.requests));
await page.screenshot({ path: "docs/shots/tmp/g9-flow-referrals.png", fullPage: true });
// manual WhatsApp state
await page.goto("http://localhost:3000/admin/alliance/requests?req=REQ-2026-0412&wa=manual", { waitUntil: "load" });
await settle(page, 1500);
const btn = page.getByRole("button", { name: /أرسل على واتساب · مكتب ط/ });
console.log("manual button count:", await btn.count());
await btn.first().click();
await settle(page, 500);
console.log("preview visible:", await page.getByText("ردّ من رابطك").count());
await page.screenshot({ path: "docs/shots/tmp/g9-flow-manual.png", fullPage: true });
await page.getByRole("button", { name: "تم الإرسال" }).click();
await settle(page, 500);
console.log("after send:", await page.getByText(/أُرسل يدوياً لمكتب ط/).count());
console.log("errors:", errs.filter((e) => !e.includes("preload")).slice(0, 5));
await browser.close();
